#!/usr/bin/env python3
"""
Convert existing SFT trajectories to special token format.

This script takes trajectories generated by the structured agent and
reformats them to use special tokens for action triggering.
"""
import json
import argparse
import sys
from pathlib import Path

# Add src to path to directly import action_tokens
sys.path.insert(0, str(Path(__file__).parent.parent / 'src'))
import action_tokens
from action_tokens import format_action_with_tokens, ALL_ACTION_TOKENS


def convert_sft_examples_to_tokens(examples: list) -> list:
    """
    Convert SFT examples to use special tokens.
    
    Args:
        examples: List of SFT example dicts
        
    Returns:
        Updated examples with special tokens
    """
    converted = []
    
    for ex in examples:
        step_type = ex.get('step_type', '').lower()
        output = ex.get('output', '')
        
        # Map step types to actions
        action_map = {
            'retrieve': 'retrieve',
            'generate_final': 'generate',
            'decompose': 'decompose',
            'extract': 'extract',
            'reason': 'reason',
        }
        
        action = action_map.get(step_type)
        
        if action:
            # For retrieve and extract, wrap the content in tokens
            if action in ['retrieve', 'extract']:
                # Extract the actual query/answer from the output text
                if 'I\'ll search for:' in output:
                    # Extract query
                    query_start = output.find('I\'ll search for:') + len('I\'ll search for:')
                    query_end = output.find('\n', query_start) if '\n' in output[query_start:] else len(output)
                    query = output[query_start:query_end].strip()
                    new_output = f"I'll search for: {format_action_with_tokens('retrieve', query)}"
                elif 'From the context, I can extract:' in output:
                    # Extract answer
                    answer_start = output.find('From the context, I can extract:') + len('From the context, I can extract:')
                    answer = output[answer_start:].strip()
                    new_output = f"From the context, I can extract: {format_action_with_tokens('extract', answer)}"
                else:
                    # Wrap the whole output
                    new_output = format_action_with_tokens(action, output)
            elif action == 'generate':
                # Generate wraps the final answer
                if 'Final answer:' in output:
                    answer = output.replace('Final answer:', '').strip()
                    new_output = f"Final answer: {format_action_with_tokens('generate', answer)}"
                else:
                    new_output = format_action_with_tokens('generate', output)
            elif action == 'decompose':
                # Decompose wraps the sub-questions
                new_output = format_action_with_tokens('decompose', output)
            else:
                new_output = output
        else:
            new_output = output
        
        converted.append({
            **ex,
            'output': new_output,
            'format_version': 'special_tokens_v1'
        })
    
    return converted


def main():
    parser = argparse.ArgumentParser(description="Convert SFT examples to special token format")
    parser.add_argument("input_file", type=str, help="Input SFT examples JSON file")
    parser.add_argument("--output", type=str, default=None, help="Output file (default: input_tokenized.json)")
    args = parser.parse_args()
    
    input_path = Path(args.input_file)
    if not input_path.exists():
        print(f"Error: Input file not found: {input_path}")
        return 1
    
    # Determine output path
    if args.output:
        output_path = Path(args.output)
    else:
        output_path = input_path.parent / f"{input_path.stem}_tokenized.json"
    
    # Load input
    print(f"Loading {input_path}...")
    with open(input_path) as f:
        data = json.load(f)
    
    examples = data.get('examples', [])
    print(f"Found {len(examples)} examples")
    
    # Convert
    print("Converting to special token format...")
    converted_examples = convert_sft_examples_to_tokens(examples)
    
    # Add token info to metadata
    metadata = data.get('metadata', {})
    metadata['format_version'] = 'special_tokens_v1'
    metadata['special_tokens'] = ALL_ACTION_TOKENS
    
    # Save
    output_data = {
        'metadata': metadata,
        'examples': converted_examples
    }
    
    print(f"Saving to {output_path}...")
    with open(output_path, 'w') as f:
        json.dump(output_data, f, indent=2)
    
    print(f"✓ Converted {len(converted_examples)} examples")
    print(f"✓ Output saved to: {output_path}")
    print(f"\nSpecial tokens used: {', '.join(ALL_ACTION_TOKENS)}")
    
    return 0


if __name__ == "__main__":
    sys.exit(main())
